#!/usr/bin/env python3
"""Generate a lineup guard: a self-contained bash script that, at each check time, swaps a starter who has been
ruled OUT (or doubtful/IR/suspended) for the best healthy, unlocked backup (via auto_swap.py).

The script runs anywhere you can leave a process running (a PC, a VPS, a Raspberry Pi): it sleeps until each check
time, skipping any that have already passed. Pass `--now` to the generated script to run the checks once,
immediately, and let cron / at / Task Scheduler / a systemd timer / GitHub Actions do the timing instead.

    python3 guard.py make --week 12 --player 4262921 --backups 4695883 4832800 \\
        --check 10:45 --check 11:20 [--league main] [--date 2026-11-29] [--shutdown-after] -o guard_wk12.sh
    ./guard_wk12.sh            # waits, then checks at 10:45 and 11:20 (America/Chicago unless --tz)
    ./guard_wk12.sh --now      # checks once, right now

Repeat --player/--backups to guard several starters in the same windows. --dry-run is passed through to
auto_swap.py, so nothing is written to ESPN.
"""
import argparse
import datetime
import os
import shlex
import stat
import sys
import zoneinfo

import config

HERE = os.path.dirname(os.path.abspath(__file__))


def check_epochs(date: datetime.date, times: list[str], tz: str) -> list[tuple[str, int]]:
    zone = zoneinfo.ZoneInfo(tz)
    out = []
    for hm in times:
        hour, minute = (int(x) for x in hm.split(":"))
        at = datetime.datetime.combine(date, datetime.time(hour, minute), tzinfo=zone)
        out.append((at.strftime("%Y-%m-%d %H:%M %Z"), int(at.timestamp())))
    return out


def render(argv: list[str], league: int, team: int, week: int, groups: list[tuple[int, list[int]]],
           checks: list[tuple[str, int]], dry_run: bool, shutdown_after: bool) -> str:
    q = shlex.quote
    swaps = []
    for player, backups in groups:
        cmd = ["python3", "auto_swap.py", "--week", week, "--league", league, "--team", team,
               "--player", player, "--backups", *backups] + (["--dry-run"] if dry_run else [])
        swaps.append("  " + " ".join(q(str(c)) for c in cmd) + ' 2>&1 | tee -a "$LOG"')
    lines = [
        "#!/usr/bin/env bash",
        "# Lineup guard generated by:",
        "#   " + " ".join(q(a) for a in argv),
        "# Checks: " + ", ".join(label for label, _ in checks),
        "# Usage: ./THIS_SCRIPT (wait for each check)   ./THIS_SCRIPT --now (check once, immediately)",
        "set -u",
        'LOG="$(cd "$(dirname "$0")" && pwd)/$(basename "${0%.sh}").log"',
        f"cd {q(HERE)} || exit 1",
        'log() { echo "[$(date \'+%Y-%m-%d %H:%M:%S\')] $*" | tee -a "$LOG"; }',
        "run_checks() {",
        *swaps,
        "}",
        'if [ "${1:-}" = "--now" ]; then',
        '  log "check (--now)"',
        "  run_checks",
        "else",
    ]
    for label, epoch in checks:
        lines += [
            f"  now=$(date +%s); target={epoch}",
            '  if [ "$now" -ge "$((target + 60))" ]; then',
            f'    log {q("skipped " + label + " (already past)")}',
            "  else",
            # Wait on the wall clock in <=30s steps: one long sleep can land early or late if the clock is
            # corrected (WSL2 resyncs) or the machine suspends mid-sleep.
            '    while now=$(date +%s); [ "$now" -lt "$target" ]; do s=$((target - now)); [ "$s" -gt 30 ] && s=30; sleep "$s"; done',
            f'    log {q("check " + label)}',
            "    run_checks",
            "  fi",
        ]
    lines.append("fi")
    if shutdown_after:
        lines += [
            'log "last check done; shutting down"',
            "if grep -qi microsoft /proc/version 2>/dev/null; then shutdown.exe /s /t 120; else shutdown -h +2; fi",
        ]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    ap = argparse.ArgumentParser(prog="guard.py", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="command", required=True)
    mk = sub.add_parser("make", help="write a guard script")
    mk.add_argument("--week", type=int, required=True, help="NFL scoring period")
    mk.add_argument("--player", type=int, action="append", required=True, help="starter to protect (repeatable)")
    mk.add_argument("--backups", type=int, nargs="+", action="append", required=True,
                    help="bench players to swap in, for the preceding --player (repeatable)")
    mk.add_argument("--check", action="append", required=True, metavar="HH:MM", help="check time (repeatable)")
    mk.add_argument("--league", help="config.json league name or ID (default: first NFL league)")
    mk.add_argument("--team", type=int, help="default: that league's team in config.json")
    mk.add_argument("--tz", default="America/Chicago", help="time zone of the check times")
    mk.add_argument("--date", help="YYYY-MM-DD (default: today in --tz)")
    mk.add_argument("--shutdown-after", action="store_true", help="power off ~2 min after the last check")
    mk.add_argument("--dry-run", action="store_true", help="pass --dry-run to auto_swap.py (no ESPN writes)")
    mk.add_argument("-o", "--output", help="write here (chmod 755) instead of stdout")
    args = ap.parse_args(argv)

    if len(args.player) != len(args.backups):
        mk.error("give one --backups list after each --player")
    for hm in args.check:
        try:
            datetime.datetime.strptime(hm, "%H:%M")
        except ValueError:
            mk.error(f"--check {hm!r} is not HH:MM")
    league, team = config.cli_league(mk, "nfl", args.league, args.team, need_team=True)
    date = (datetime.date.fromisoformat(args.date) if args.date
            else datetime.datetime.now(zoneinfo.ZoneInfo(args.tz)).date())
    checks = sorted(check_epochs(date, args.check, args.tz), key=lambda c: c[1])
    script = render(["guard.py", *argv], league, team, args.week, list(zip(args.player, args.backups)),
                    checks, args.dry_run, args.shutdown_after)
    if args.output:
        with open(args.output, "w") as f:
            f.write(script)
        os.chmod(args.output, os.stat(args.output).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        print(f"wrote {args.output}: " + ", ".join(label for label, _ in checks))
    else:
        sys.stdout.write(script)
    return 0


if __name__ == "__main__":
    sys.exit(main())
